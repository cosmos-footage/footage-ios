struct CityDotGrid: Equatable {
    struct Point: Equatable, Hashable {
        let row: Int
        let column: Int
    }

    static let side = 15

    let id: String
    let imageName: String
    let displayName: String
    let sourceName: String
    let sourceCode: String
    let mask: [String]

    var points: [Point] {
        mask.enumerated().flatMap { row, line in
            line.enumerated().compactMap { column, value in
                value == "#" ? Point(row: row, column: column) : nil
            }
        }
    }

    static func grid(imageName: String) -> CityDotGrid? {
        let baseName = ["_newb", "_junior", "_master"].reduce(imageName) { name, suffix in
            name.hasSuffix(suffix) ? String(name.dropLast(suffix.count)) : name
        }

        return all.first { $0.imageName == baseName }
    }

    static func grid(sourceName: String) -> CityDotGrid? {
        all.first {
            $0.imageName == sourceName ||
            $0.displayName == sourceName ||
            $0.sourceName == sourceName
        }
    }

